"""Upstox Market Data Feed V3 protobuf bindings.

MarketDataFeedV3.proto is Upstox's official schema. The Python module is generated with
grpcio-tools on first use (or at image build via `python -m app.marketdata.upstox.proto`), so the
generated code always matches the installed protobuf runtime.
"""

import importlib
from functools import lru_cache
from pathlib import Path
from types import ModuleType

_DIR = Path(__file__).parent
_PROTO = _DIR / "MarketDataFeedV3.proto"
_MODULE = f"{__name__}.MarketDataFeedV3_pb2"


def compile_proto() -> None:
    import grpc_tools
    from grpc_tools import protoc

    include = Path(grpc_tools.__file__).parent / "_proto"
    rc = protoc.main(
        ["protoc", f"-I{_DIR}", f"-I{include}", f"--python_out={_DIR}", str(_PROTO)]
    )
    if rc != 0:
        raise RuntimeError(f"protoc failed compiling {_PROTO} (exit {rc})")
    importlib.invalidate_caches()


@lru_cache
def feed_pb() -> ModuleType:
    try:
        return importlib.import_module(_MODULE)
    except Exception:  # missing, or generated by an incompatible protobuf version
        compile_proto()
        return importlib.import_module(_MODULE)
